#!/usr/bin/env python3
"""
One table of app wording for BOTH apps (English only) -> each platform's string files.

Source:  tools/i18n/strings/*.json   {"key": "English text", ...}
         Placeholders are {0}, {1}, ... (always strings).
Output:  android-app/app/src/main/res/values/strings.xml
         ios-app/ScamGuard/Localizable.xcstrings           (String Catalog, English)
         ios-app/ScamGuard/Logic/L10nKeys.swift             (enum K: every key, so a typo doesn't compile)

Run:     python3 tools/i18n/gen_strings.py
Edit the JSON, never the generated files.
"""
import glob
import json
import os
import re
import sys
from xml.sax.saxutils import escape as xml_escape

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "tools", "i18n", "strings")
ANDROID_RES = os.path.join(ROOT, "android-app", "app", "src", "main", "res")
IOS_DIR = os.path.join(ROOT, "ios-app", "ScamGuard")
KEY_RE = re.compile(r"^[a-z][a-z0-9_]*$")
ARG_RE = re.compile(r"\{(\d)\}")


def load():
    table, origin = {}, {}
    for path in sorted(glob.glob(os.path.join(SRC, "*.json"))):
        with open(path, encoding="utf-8") as f:
            data = json.load(f)
        for key, text in data.items():
            if not KEY_RE.match(key):
                sys.exit(f"{path}: bad key {key!r} (lowercase, digits, _)")
            if key in table:
                sys.exit(f"{path}: duplicate key {key!r} (also in {origin[key]})")
            if not isinstance(text, str) or not text:
                sys.exit(f"{path}: {key} must be a non-empty string")
            table[key] = text
            origin[key] = os.path.basename(path)
    return table


def args_of(text):
    return sorted(set(int(a) for a in ARG_RE.findall(text)))


def check(table):
    problems = []
    for key, text in table.items():
        want = args_of(text)
        if want and want != list(range(len(want))):
            problems.append(f"{key}: placeholders must be {{0}}..{{n}} in order: {want}")
    if problems:
        sys.exit("Placeholder problems:\n  " + "\n  ".join(problems))


# ---------------------------------------------------------------- Android

def android_text(text):
    has_args = bool(ARG_RE.search(text))
    if has_args:
        text = text.replace("%", "%%")
    t = xml_escape(text)
    t = t.replace("\\", "\\\\").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if t.startswith("@") or t.startswith("?"):
        t = "\\" + t
    t = ARG_RE.sub(lambda m: f"%{int(m.group(1)) + 1}$s", t)
    return t, has_args


def write_android(table):
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- Generated by tools/i18n/gen_strings.py from tools/i18n/strings/*.json. Edit those, not this file. -->",
             "<resources>",
             '    <string name="app_name">ScamGuard</string>']
    for key in sorted(table):
        text, has_args = android_text(table[key])
        attrs = ' formatted="false"' if not has_args and "%" in text else ""
        lines.append(f'    <string name="{key}"{attrs}>{text}</string>')
    lines.append("</resources>")
    d = os.path.join(ANDROID_RES, "values")
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "strings.xml"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


# ---------------------------------------------------------------- iOS

def ios_text(text):
    if ARG_RE.search(text):
        text = text.replace("%", "%%")
        text = ARG_RE.sub(lambda m: f"%{int(m.group(1)) + 1}$@", text)
    return text


def write_ios(table):
    strings = {}
    for key in sorted(table):
        strings[key] = {
            "comment": "Source: tools/i18n/strings/*.json",
            "extractionState": "manual",
            "localizations": {"en": {"stringUnit": {"state": "translated", "value": ios_text(table[key])}}},
        }
    catalog = {"sourceLanguage": "en", "strings": strings, "version": "1.0"}
    with open(os.path.join(IOS_DIR, "Localizable.xcstrings"), "w", encoding="utf-8") as f:
        json.dump(catalog, f, ensure_ascii=False, indent=2, sort_keys=True)
        f.write("\n")
    out = ["// Generated by tools/i18n/gen_strings.py. Do not edit: change tools/i18n/strings/*.json instead.",
           "// Every app string key, so a typo is a compile error. Look a key up with L.s(.key, args...).",
           "",
           "nonisolated enum K: String, CaseIterable, Sendable {"]
    for key in sorted(table):
        out.append(f"    case {key}")
    out.append("}")
    with open(os.path.join(IOS_DIR, "Logic", "L10nKeys.swift"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


def main():
    table = load()
    check(table)
    write_android(table)
    write_ios(table)
    print(f"{len(table)} keys")


if __name__ == "__main__":
    main()
