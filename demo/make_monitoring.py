#!/usr/bin/env python3
"""make_monitoring.py - Workstream H.1/H.2: Prometheus + Grafana for the learning loop (OPTIONAL).

Writes demo/k8s/monitoring/{prometheus,grafana}.yaml. They live in a sub-folder on purpose: `kubectl apply -f
demo/k8s/` does not recurse, so the ~400 MB they use is only spent when you ask for it:
    python demo/tools/learning.py monitoring up      (apply + open Grafana on http://127.0.0.1:3000)
    python demo/tools/learning.py monitoring down

What Prometheus scrapes (counts only, never text):
  aggregator  every pod's :8082/metrics (found by DNS on the headless aggregator-hl Service, so no RBAC)
  review      review:8090/metrics (queue size, labels not yet trained on, newest released model version)

Drift alert (H.2) "PossibleNewScam": the UNSURE share, or the worker/BERT disagreement rate, over the last
DRIFT_SHORT is DRIFT_FACTOR x its level over the DRIFT_BASELINE before. It shows on the Grafana dashboard and
on Prometheus' Alerts page (no Alertmanager: nobody gets paged in a demo).

Called by make_manifests.py; can also run alone:  python demo/make_monitoring.py
"""
import json
from pathlib import Path

OUT_DIR = Path(__file__).resolve().parent / "k8s" / "monitoring"


def indent(text: str, n: int) -> str:
    pad = " " * n
    return "\n".join(pad + line if line else line for line in text.splitlines())


def prometheus_yaml(ns, short, baseline, factor, min_share, image) -> str:
    config = f"""global:
  scrape_interval: 15s
  evaluation_interval: 30s
rule_files: [/etc/prometheus/rules.yml]
scrape_configs:
  - job_name: aggregator
    dns_sd_configs:
      - names: [aggregator-hl.{ns}.svc.cluster.local]
        type: A
        port: 8082
  - job_name: review
    static_configs:
      - targets: [review.{ns}.svc.cluster.local:8090]
"""
    lines = "sum(rate(scamguard_lines_total[{w}]))"
    unsure = 'sum(rate(scamguard_lines_total{{verdict="UNSURE"}}[{w}]))'
    disagree = "sum(rate(scamguard_disagreements_total[{w}]))"
    compared = "sum(rate(scamguard_bert_compared_total[{w}]))"
    rules = f"""groups:
  - name: scamguard
    rules:
      # Shares over the short window, recorded so the baseline can average them over the long one.
      - record: scamguard:unsure_share:short
        expr: {unsure.format(w=short)} / {lines.format(w=short)}
      - record: scamguard:disagreement_rate:short
        expr: {disagree.format(w=short)} / {compared.format(w=short)}
      - record: scamguard:lines_per_second:short
        expr: {lines.format(w=short)}
      - alert: PossibleNewScam
        expr: |
          (
            scamguard:unsure_share:short > {factor} * avg_over_time(scamguard:unsure_share:short[{baseline}] offset {short})
            and scamguard:unsure_share:short > {min_share}
          )
          or
          (
            scamguard:disagreement_rate:short > {factor} * avg_over_time(scamguard:disagreement_rate:short[{baseline}] offset {short})
            and scamguard:disagreement_rate:short > 0.1
          )
        for: 5m
        labels: {{ severity: info }}
        annotations:
          summary: "More UNSURE answers or worker/BERT disagreement than usual: a new scam script may be circulating."
          action: "Check the review queue for reported calls; label them and run the retraining Job."
"""
    return f"""# Generated by demo/make_monitoring.py -- edit that, not this.
apiVersion: v1
kind: ConfigMap
metadata:
  name: prometheus-config
  namespace: {ns}
data:
  prometheus.yml: |
{indent(config, 4)}
  rules.yml: |
{indent(rules, 4)}
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: prometheus
  namespace: {ns}
  labels: {{ app: prometheus }}
spec:
  replicas: 1
  selector:
    matchLabels: {{ app: prometheus }}
  template:
    metadata:
      labels: {{ app: prometheus }}
    spec:
      containers:
        - name: prometheus
          image: {image}
          args:
            - --config.file=/etc/prometheus/prometheus.yml
            - --storage.tsdb.path=/prometheus
            - --storage.tsdb.retention.time=3d
          ports:
            - containerPort: 9090
          resources:
            requests: {{ cpu: 50m, memory: 128Mi }}
            limits: {{ cpu: 500m, memory: 384Mi }}
          readinessProbe:
            httpGet: {{ path: /-/ready, port: 9090 }}
            periodSeconds: 10
          volumeMounts:
            - {{ name: config, mountPath: /etc/prometheus }}
            - {{ name: data, mountPath: /prometheus }}
      volumes:
        - name: config
          configMap: {{ name: prometheus-config }}
        - name: data
          emptyDir: {{}}
---
apiVersion: v1
kind: Service
metadata:
  name: prometheus
  namespace: {ns}
spec:
  selector: {{ app: prometheus }}
  ports:
    - {{ name: http, port: 9090, targetPort: 9090 }}
"""


def panel(pid, title, targets, x, y, w=12, h=8, unit="short", kind="timeseries", desc="", stack=False, maxv=None):
    p = {"id": pid, "type": kind, "title": title, "description": desc,
         "gridPos": {"x": x, "y": y, "w": w, "h": h},
         "datasource": {"type": "prometheus", "uid": "prometheus"},
         "targets": [{"refId": chr(65 + i), "expr": e, "legendFormat": leg,
                      "datasource": {"type": "prometheus", "uid": "prometheus"}} for i, (e, leg) in enumerate(targets)],
         "fieldConfig": {"defaults": {"unit": unit}, "overrides": []}, "options": {}}
    if maxv is not None:
        p["fieldConfig"]["defaults"]["max"] = maxv
        p["fieldConfig"]["defaults"]["min"] = 0
    if kind == "timeseries":
        p["fieldConfig"]["defaults"]["custom"] = {"fillOpacity": 20 if stack else 0, "lineWidth": 2,
                                                  "stacking": {"mode": "normal" if stack else "none"}}
        p["options"] = {"legend": {"displayMode": "list", "placement": "bottom"}}
    return p


def dashboard(short, baseline) -> dict:
    w = "5m"
    share = 'sum by (verdict) (rate(scamguard_lines_total[{w}])) / ignoring(verdict) group_left sum(rate(scamguard_lines_total[{w}]))'
    panels = [
        panel(1, "Possible new scam (drift alert)", [('count(ALERTS{alertname="PossibleNewScam",alertstate="firing"}) or vector(0)', "firing")],
              0, 0, w=6, h=5, kind="stat", desc="1 = the UNSURE share or worker/BERT disagreement is well above its usual level."),
        panel(2, "Calls started (per minute)", [("sum(rate(scamguard_calls_started_total[5m])) * 60", "calls/min")], 6, 0, w=6, h=5, kind="stat"),
        panel(3, "Reports waiting to be labelled", [("review_lines_unlabelled", "lines")], 12, 0, w=6, h=5, kind="stat"),
        panel(4, "Newest released urgency_en model", [('review_model_latest{name="urgency_en"}', "v")], 18, 0, w=6, h=5, kind="stat",
              desc="Version number in the registry (5 = v5). Rolled out separately with learning.py rollout."),
        panel(5, "Verdict share per call (final verdict)",
              [('sum by (verdict) (increase(scamguard_calls_final_total[1h])) / ignoring(verdict) group_left '
                'sum(increase(scamguard_calls_final_total[1h]))', "{{verdict}} (calls)"),
               (share.format(w=w), "{{verdict}} (lines)")], 0, 5, unit="percentunit", maxv=1,
              desc="Calls: the share of calls that ended SAFE / UNSURE / SCAM in the last hour. Lines: per caller line."),
        panel(6, f"UNSURE share: now vs usual ({short} window)",
              [("scamguard:unsure_share:short", "last " + short),
               (f"avg_over_time(scamguard:unsure_share:short[{baseline}] offset {short})", f"usual ({baseline} before)")],
              12, 5, unit="percentunit", maxv=1),
        panel(7, "Worker / BERT disagreement rate",
              [("scamguard:disagreement_rate:short", "share of BERT answers"),
               (f"avg_over_time(scamguard:disagreement_rate:short[{baseline}] offset {short})", f"usual ({baseline} before)"),
               ('sum by (direction) (rate(scamguard_disagreements_total[5m])) * 60', "{{direction}} per min")],
              0, 13, desc="bert_safer: workers alarmed, BERT says safe. bert_riskier: workers calm, BERT says scam."),
        panel(8, "BERT second opinion outcomes (per min)", [("sum by (status) (rate(scamguard_bert_total[5m])) * 60", "{{status}}")],
              12, 13, stack=True),
        panel(9, "Average score per signal",
              [("sum by (signal) (rate(scamguard_signal_score_sum[5m])) / sum by (signal) (rate(scamguard_signal_score_count[5m]))", "{{signal}}")],
              0, 21, unit="percentunit", maxv=1),
        panel(10, "Review queue", [("review_lines_unlabelled", "waiting for a label"),
                                   ('review_labels_unused{signal="urgency"}', "urgency labels not trained on yet"),
                                   ("sum(review_labels_disputed)", "disputed by a spot check")], 12, 21),
        panel(11, "Missed scams reported by users", [('sum(review_reports_received_total{kind="scam",app_verdict="SAFE"})', "app said SAFE"),
                                                    ('sum(review_reports_received_total{kind="scam",app_verdict="UNSURE"})', "app said UNSURE")],
              0, 29, desc="\"This was a scam\" reports on calls the app did not turn red. A rising count is a new-scam signal that needs no text."),
    ]
    return {"uid": "scamguard-learning", "title": "ScamGuard: learning new scams", "schemaVersion": 39,
            "time": {"from": "now-1h", "to": "now"}, "refresh": "15s", "tags": ["scamguard"], "panels": panels}


def grafana_yaml(ns, short, baseline, image) -> str:
    datasource = """apiVersion: 1
datasources:
  - name: Prometheus
    uid: prometheus
    type: prometheus
    url: http://prometheus:9090
    isDefault: true
"""
    provider = """apiVersion: 1
providers:
  - name: scamguard
    type: file
    options:
      path: /var/lib/grafana/dashboards
"""
    return f"""# Generated by demo/make_monitoring.py -- edit that, not this.
apiVersion: v1
kind: ConfigMap
metadata:
  name: grafana-provisioning
  namespace: {ns}
data:
  datasource.yml: |
{indent(datasource, 4)}
  dashboards.yml: |
{indent(provider, 4)}
---
apiVersion: v1
kind: ConfigMap
metadata:
  name: grafana-dashboards
  namespace: {ns}
data:
  scamguard.json: |
{indent(json.dumps(dashboard(short, baseline), indent=2), 4)}
---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: grafana
  namespace: {ns}
  labels: {{ app: grafana }}
spec:
  replicas: 1
  selector:
    matchLabels: {{ app: grafana }}
  template:
    metadata:
      labels: {{ app: grafana }}
    spec:
      containers:
        - name: grafana
          image: {image}
          env:
            # Read-only view without a login; only reachable through kubectl port-forward.
            - {{ name: GF_AUTH_ANONYMOUS_ENABLED, value: "true" }}
            - {{ name: GF_AUTH_ANONYMOUS_ORG_ROLE, value: Viewer }}
            - {{ name: GF_DASHBOARDS_DEFAULT_HOME_DASHBOARD_PATH, value: /var/lib/grafana/dashboards/scamguard.json }}
            - {{ name: GF_ANALYTICS_REPORTING_ENABLED, value: "false" }}
            - {{ name: GF_ANALYTICS_CHECK_FOR_UPDATES, value: "false" }}
          ports:
            - containerPort: 3000
          resources:
            requests: {{ cpu: 50m, memory: 96Mi }}
            limits: {{ cpu: 500m, memory: 256Mi }}
          readinessProbe:
            httpGet: {{ path: /api/health, port: 3000 }}
            periodSeconds: 10
          volumeMounts:
            - {{ name: provisioning, mountPath: /etc/grafana/provisioning/datasources/datasource.yml, subPath: datasource.yml }}
            - {{ name: provisioning, mountPath: /etc/grafana/provisioning/dashboards/dashboards.yml, subPath: dashboards.yml }}
            - {{ name: dashboards, mountPath: /var/lib/grafana/dashboards }}
      volumes:
        - name: provisioning
          configMap: {{ name: grafana-provisioning }}
        - name: dashboards
          configMap: {{ name: grafana-dashboards }}
---
apiVersion: v1
kind: Service
metadata:
  name: grafana
  namespace: {ns}
spec:
  selector: {{ app: grafana }}
  ports:
    - {{ name: http, port: 3000, targetPort: 3000 }}
"""


def main(ns="scamguard", short="1h", baseline="1d", factor="1.5", min_share="0.15",
         prom_image="prom/prometheus:v3.1.0", grafana_image="grafana/grafana:11.4.0"):
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in (("prometheus.yaml", prometheus_yaml(ns, short, baseline, factor, min_share, prom_image)),
                       ("grafana.yaml", grafana_yaml(ns, short, baseline, grafana_image))):
        (OUT_DIR / name).write_text(text, encoding="utf-8")
        print(f"wrote {OUT_DIR / name}")


if __name__ == "__main__":
    main()
