// Copies the two vendored libraries into web/ (their output is committed; nothing is fetched at runtime):
//   vendor/preact-htm.js  Preact + hooks + htm in one ES module (htm 3.1.1 "preact/standalone", Apache-2.0 / MIT)
//   js/ui/icons.js        the Lucide icons the app uses (lucide-static 0.460.0, ISC), as inline SVG bodies
// Run from web/: npm install && npm run vendor
import { readFileSync, writeFileSync, copyFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const nm = join(web, "node_modules");
mkdirSync(join(web, "vendor"), { recursive: true });

const preact = readFileSync(join(nm, "htm/preact/standalone.module.js"), "utf8");
writeFileSync(join(web, "vendor/preact-htm.js"),
  "/* Preact 10 + hooks + htm 3.1.1 (htm/preact/standalone.module.js). Preact: MIT (c) Jason Miller; htm: Apache-2.0 " +
  "(c) Google LLC. Licences: vendor/LICENSE-htm, vendor/LICENSE-lucide. */\n" + preact);
copyFileSync(join(nm, "htm/LICENSE"), join(web, "vendor/LICENSE-htm"));
copyFileSync(join(nm, "lucide-static/LICENSE"), join(web, "vendor/LICENSE-lucide"));

// SF Symbol (iOS app) -> closest Lucide icon. Key = the name the web app uses.
const ICONS = {
  house: "house", list: "layout-list", settings: "settings", phone: "phone", "phone-off": "phone-off",
  x: "x", check: "check", info: "info", star: "star", lock: "lock", "shield-check": "shield-check", user: "user",
  smile: "smile", "text-size": "a-large-small", help: "circle-help", hammer: "hammer", antenna: "radio-tower",
  send: "send", share: "share", "chevron-right": "chevron-right", "chevron-left": "chevron-left",
  "chevron-down": "chevron-down", "chevron-up": "chevron-up", alert: "triangle-alert", "circle-check": "circle-check",
  "circle-info": "info", heart: "heart", "list-plain": "list", play: "play", cloud: "cloud", smartphone: "smartphone",
  copy: "copy", trash: "trash-2", refresh: "refresh-cw", users: "users", volume: "volume-2",
};
const out = {};
for (const [key, file] of Object.entries(ICONS)) {
  const svg = readFileSync(join(nm, "lucide-static/icons", file + ".svg"), "utf8");
  out[key] = svg.slice(svg.indexOf(">", svg.indexOf("<svg")) + 1, svg.lastIndexOf("</svg>")).replace(/\s*\n\s*/g, "").trim();
}
writeFileSync(join(web, "js/ui/icons.js"),
  "// Generated by tools/vendor.mjs from lucide-static 0.460.0 (ISC licence, vendor/LICENSE-lucide). Do not edit.\n" +
  "// Each value is the inside of a 24x24 Lucide SVG (stroke = currentColor).\n" +
  "export const ICONS = " + JSON.stringify(out, null, 1) + ";\n");
console.log(`vendor/preact-htm.js (${preact.length} bytes), ${Object.keys(out).length} icons`);
