// Workstream E: DEBUG builds also trust this laptop's demo CA (demo/tls/ca.crt, made by demo/make_tls.py), built into
// the app, so a phone needs no certificate installed (installing a user CA is fiddly, and some Android versions /
// install types don't make it a trust anchor). Release builds don't get it: they trust only the system CAs.
// The CA is per laptop and not in git, so it's read at build time; without it the debug config is the same as main.
val demoCaFile = rootProject.file("../demo/tls/ca.crt")
val demoCaOut = layout.buildDirectory.dir("generated/demoCa/res")
val demoCaConfig = tasks.register("demoCaConfig") {
    val caText = if (demoCaFile.isFile) demoCaFile.readText() else ""
    inputs.property("ca", caText)
    val out = demoCaOut
    outputs.dir(out)
    doLast {
        val dir = out.get().asFile
        dir.deleteRecursively()
        File(dir, "xml").mkdirs()
        var bundled = ""
        if (caText.isNotEmpty()) {
            File(dir, "raw").mkdirs()
            File(dir, "raw/scamguard_demo_ca.pem").writeText(caText)
            bundled = "\n            <certificates src=\"@raw/scamguard_demo_ca\" />"
        }
        File(dir, "xml/network_security_config.xml").writeText(
            """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/build.gradle.kts (demoCaConfig) for debug builds: main's config + the laptop's demo CA. -->
<network-security-config>
    <base-config cleartextTrafficPermitted="true">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>
    <debug-overrides>
        <trust-anchors>
            <certificates src="user" />$bundled
        </trust-anchors>
    </debug-overrides>
</network-security-config>
""")
    }
}
android.sourceSets.getByName("debug").res.directories.add("${layout.buildDirectory.get().asFile}/generated/demoCa/res")
tasks.matching { it.name == "preBuild" }.configureEach { dependsOn(demoCaConfig) }

